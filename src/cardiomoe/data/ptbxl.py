"""PTB-XL loading, labels, metadata cleaning and splits (Sections 5.1-5.4).

    python -m cardiomoe.data.ptbxl --prepare [--debug]

Writes to data/processed/ (or data/processed/debug/ with --debug):
    ptbxl_meta.parquet     one row per kept record: ids, fold, split, labels, Client A features
    ptbxl_signals.npy      float16 [N, 12, 1000] filtered, un-normalised signal in mV (row = meta.row)
    tabular_stats.json     train-set imputation/standardisation statistics (reused for Chapman)
"""
from __future__ import annotations

import argparse
import json
import logging
from multiprocessing import Pool
from pathlib import Path

import numpy as np
import pandas as pd
import wfdb
from tqdm import tqdm

from cardiomoe.data import labels as L
from cardiomoe.data.signal import preprocess
from cardiomoe.utils import load_config, repo_path, set_seed

log = logging.getLogger(__name__)

TRAIN_FOLDS = list(range(1, 9))
VAL_FOLD, TEST_FOLD = 9, 10

# Section 5.3: the only metadata columns Client A may see.
TABULAR_SOURCE_COLUMNS = ["age", "sex", "height", "weight"]
FEATURE_COLUMNS = ["age", "sex", "height", "weight", "bmi", "height_missing", "weight_missing"]
# Never features: label sources, annotations, signal-quality notes.
FORBIDDEN_COLUMNS = [
    "scp_codes", "report", "infarction_stadium1", "infarction_stadium2", "heart_axis",
    "extra_beats", "pacemaker", "validated_by", "second_opinion",
    "initial_autogenerated_report", "validated_by_human",
    "baseline_drift", "static_noise", "burst_noise", "electrodes_problems",
]
AGE_CAP = 90  # PTB-XL stores 300 for ages > 89


def processed_dir(cfg: dict, debug: bool) -> Path:
    d = repo_path(cfg["paths"]["processed"]) / ("debug" if debug else "")
    d.mkdir(parents=True, exist_ok=True)
    return d


def split_of(fold: int) -> str:
    return "test" if fold == TEST_FOLD else "val" if fold == VAL_FOLD else "train"


# --------------------------------------------------------------------------- tabular
def tabular_features(demo: pd.DataFrame, stats: dict | None = None) -> tuple[pd.DataFrame, dict]:
    """demo has TABULAR_SOURCE_COLUMNS (height/weight may be NaN; sex 0 = male, 1 = female).

    If stats is None they are computed from demo (pass the *train* rows only).
    Returns standardised FEATURE_COLUMNS and the stats used.
    """
    df = demo[TABULAR_SOURCE_COLUMNS].astype(float).copy()
    df["age"] = df["age"].clip(upper=AGE_CAP)
    df["height_missing"] = df["height"].isna().astype(float)
    df["weight_missing"] = df["weight"].isna().astype(float)
    df["bmi"] = df["weight"] / (df["height"] / 100.0) ** 2  # NaN unless both present

    if stats is None:
        stats = {"median": {c: float(df[c].median()) for c in ["age", "height", "weight", "bmi"]}}
        stats["median"]["sex"] = float(df["sex"].mode().iloc[0])
    for c in ["age", "sex", "height", "weight", "bmi"]:
        df[c] = df[c].fillna(stats["median"][c])
    if "mean" not in stats:
        stats["mean"] = {c: float(df[c].mean()) for c in ["age", "height", "weight", "bmi"]}
        stats["std"] = {c: float(df[c].std()) for c in ["age", "height", "weight", "bmi"]}
    for c in ["age", "height", "weight", "bmi"]:
        df[c] = (df[c] - stats["mean"][c]) / stats["std"][c]
    return df[FEATURE_COLUMNS].astype(np.float32), stats


# --------------------------------------------------------------------------- loading
def load_database(raw: Path) -> tuple[pd.DataFrame, pd.DataFrame]:
    db = pd.read_csv(raw / "ptbxl_database.csv", index_col="ecg_id")
    scp = pd.read_csv(raw / "scp_statements.csv", index_col=0)
    return db, scp


def build_meta(db: pd.DataFrame, scp: pd.DataFrame) -> pd.DataFrame:
    code_map = L.diagnostic_map(scp)
    classes = db.scp_codes.apply(lambda s: L.ptbxl_superclasses(s, code_map))
    keep = classes.str.len() > 0
    log.info("dropped %d / %d records with no diagnostic superclass", (~keep).sum(), len(db))
    db, classes = db[keep], classes[keep]

    meta = pd.DataFrame(index=db.index)
    meta["patient_id"] = db.patient_id.astype(int)
    meta["strat_fold"] = db.strat_fold.astype(int)
    meta["split"] = meta.strat_fold.map(split_of)
    meta["filename_lr"] = db.filename_lr
    y = np.stack(classes.apply(L.multi_hot).values)
    for i, c in enumerate(L.SUPERCLASSES):
        meta[f"y_{c}"] = y[:, i]

    train = meta.split == "train"
    _, stats = tabular_features(db.loc[train, TABULAR_SOURCE_COLUMNS])
    feats, _ = tabular_features(db[TABULAR_SOURCE_COLUMNS], stats)
    for c in FEATURE_COLUMNS:
        meta[f"x_{c}"] = feats[c]
    meta.attrs["tabular_stats"] = stats
    meta.attrs["n_dropped"] = int((~keep).sum())
    return meta


def _read_one(path: str) -> tuple[np.ndarray, int]:
    sig, info = wfdb.rdsamp(path)
    return preprocess(sig, int(info["fs"]), info["sig_name"])


def load_signals(raw: Path, filenames: list[str], workers: int = 8) -> np.ndarray:
    paths = [str(raw / f) for f in filenames]
    with Pool(workers) as pool:
        out = list(tqdm(pool.imap(_read_one, paths, chunksize=64), total=len(paths), desc="ptbxl signals"))
    n_nan = sum(n for _, n in out)
    log.info("replaced %d NaN/inf samples with 0 across %d records", n_nan, len(out))
    return np.stack([s for s, _ in out]).astype(np.float16)


def prevalence_table(meta: pd.DataFrame) -> pd.DataFrame:
    ycols = [f"y_{c}" for c in L.SUPERCLASSES]
    t = meta.groupby("split")[ycols].mean().rename(columns=lambda c: c[2:])
    t.insert(0, "n_records", meta.groupby("split").size())
    t.insert(1, "n_patients", meta.groupby("split").patient_id.nunique())
    return t.loc[[s for s in ["train", "val", "test"] if s in t.index]]


# --------------------------------------------------------------------------- public API
def load_meta(cfg: dict, debug: bool = False) -> pd.DataFrame:
    return pd.read_parquet(processed_dir(cfg, debug) / "ptbxl_meta.parquet")


def load_signal_array(cfg: dict, debug: bool = False) -> np.ndarray:
    return np.load(processed_dir(cfg, debug) / "ptbxl_signals.npy", mmap_mode="r")


def prepare(cfg: dict, debug: bool) -> pd.DataFrame:
    raw = repo_path(cfg["paths"]["ptbxl"])
    out = processed_dir(cfg, debug)
    db, scp = load_database(raw)
    meta = build_meta(db, scp)
    if debug:
        meta = meta.sample(n=min(cfg["debug_n_samples"], len(meta)), random_state=cfg["seed"]).sort_index()
    meta["row"] = np.arange(len(meta))

    sig = load_signals(raw, meta.filename_lr.tolist(), workers=1 if debug else 8)
    np.save(out / "ptbxl_signals.npy", sig)
    stats = meta.attrs.pop("tabular_stats")
    (out / "tabular_stats.json").write_text(json.dumps(stats, indent=2))
    meta.attrs.clear()
    meta.to_parquet(out / "ptbxl_meta.parquet")

    prev = prevalence_table(meta)
    tables = repo_path(cfg["paths"]["tables"])
    tables.mkdir(parents=True, exist_ok=True)
    prev.to_csv(tables / f"ptbxl_prevalence{'_debug' if debug else ''}.csv")
    print(f"kept {len(meta)} records -> {out}")
    print(prev.round(3).to_string())
    return meta


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--prepare", action="store_true")
    ap.add_argument("--debug", action="store_true")
    args = ap.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    cfg = load_config()
    set_seed(cfg["seed"])
    if args.prepare:
        prepare(cfg, args.debug)


if __name__ == "__main__":
    main()
